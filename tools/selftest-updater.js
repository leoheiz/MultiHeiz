'use strict';

/**
 * Offline selftest for updater module + portable self-update flow.
 * Uso: npm run selftest:updater
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const http = require('node:http');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');

const root = path.join(__dirname, '..');

function assert(cond, msg) {
  if (!cond) {
    console.log('FAIL:', msg);
    process.exit(1);
  }
}

/** Minimal electron stub so updater.js can load without Electron. */
function installElectronStub(opts = {}) {
  const electronPath = require.resolve('electron');
  const stub = {
    app: {
      isPackaged: !!opts.isPackaged,
      getVersion: () => opts.version || '1.0.1',
      getPath: (name) => {
        if (name === 'temp') return opts.tempDir || os.tmpdir();
        return opts.tempDir || os.tmpdir();
      },
      quit() {},
    },
    ipcMain: {
      removeHandler() {},
      handle() {},
    },
    shell: {
      openExternal() {},
      showItemInFolder() {},
      openPath() {},
    },
  };
  require.cache[electronPath] = {
    id: electronPath,
    filename: electronPath,
    loaded: true,
    exports: stub,
  };
  const orig = Module._resolveFilename;
  Module._resolveFilename = function (request, parent, isMain, options) {
    if (request === 'electron') return electronPath;
    return orig.call(this, request, parent, isMain, options);
  };
  return stub;
}

function clearUpdaterModules() {
  for (const key of Object.keys(require.cache)) {
    if (
      key.replace(/\\/g, '/').includes('/src/main/updater') ||
      key.replace(/\\/g, '/').includes('/src/main/portable-update')
    ) {
      delete require.cache[key];
    }
  }
}

async function main() {
  console.log('MultiHeiz selftest:updater');
  const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'mh-upd-'));
  const stub = installElectronStub({
    isPackaged: false,
    version: '1.0.1',
    tempDir: tempRoot,
  });

  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const publish = pkg.build && pkg.build.publish;
  assert(Array.isArray(publish) && publish.length > 0, 'build.publish missing');
  const gh = publish[0];
  assert(gh.provider === 'github', 'publish provider');
  assert(gh.owner === 'leoheiz', 'publish owner leoheiz');
  assert(gh.repo === 'MultiHeiz', 'publish repo MultiHeiz');
  assert(gh.releaseType === 'release', 'releaseType release');
  console.log('PASS: publish config github leoheiz/MultiHeiz');

  assert(pkg.dependencies && pkg.dependencies['electron-updater'], 'electron-updater dep');
  assert(pkg.version === '1.1.0', 'package version 1.1.0');
  console.log('PASS: electron-updater in dependencies, version 1.1.0');

  // app-update.yml is generated by electron-builder when publish is set (nsis)
  assert(pkg.build.publish[0].provider === 'github', 'publish enables app-update.yml generation');
  console.log('PASS: publish config present for app-update.yml');

  let updater = require('../src/main/updater');
  assert(updater.GITHUB_OWNER === 'leoheiz', 'GITHUB_OWNER');
  assert(updater.GITHUB_REPO === 'MultiHeiz', 'GITHUB_REPO');

  const prevDir = process.env.PORTABLE_EXECUTABLE_DIR;
  const prevFile = process.env.PORTABLE_EXECUTABLE_FILE;
  delete process.env.PORTABLE_EXECUTABLE_DIR;
  delete process.env.PORTABLE_EXECUTABLE_FILE;
  process.env.PORTABLE_EXECUTABLE_DIR = 'C:\\portable';
  assert(updater.detectUpdateChannel() === 'portable', 'portable via DIR');
  assert(!updater.isManualOnlyChannel('portable'), 'portable is NOT manual-only anymore');
  delete process.env.PORTABLE_EXECUTABLE_DIR;
  process.env.PORTABLE_EXECUTABLE_FILE = 'C:\\MultiHeiz-portable.exe';
  assert(updater.detectUpdateChannel() === 'portable', 'portable via FILE');
  delete process.env.PORTABLE_EXECUTABLE_FILE;
  if (prevDir !== undefined) process.env.PORTABLE_EXECUTABLE_DIR = prevDir;
  if (prevFile !== undefined) process.env.PORTABLE_EXECUTABLE_FILE = prevFile;
  console.log('PASS: portable detection (self-update channel)');

  assert(updater.isManualOnlyChannel('deb'), 'deb is manual');
  assert(!updater.isManualOnlyChannel('nsis'), 'nsis not manual');
  assert(!updater.isManualOnlyChannel('appimage'), 'appimage not manual');
  console.log('PASS: portable/deb channel logic');

  assert(updater.compareSemver('1.0.10', '1.0.9') > 0, '1.0.10 > 1.0.9');
  assert(updater.compareSemver('1.0.1', '1.1.0') < 0, '1.0.1 < 1.1.0');
  console.log('PASS: semver compare incl. 1.0.10 > 1.0.9');

  const enabledDefault = updater.getAutoCheckEnabled(() => ({ settings: {} }));
  assert(enabledDefault === true, 'autoCheck default ON when unset');
  console.log('PASS: autoCheckUpdates default ON');

  const srcFiles = [
    path.join(root, 'src', 'main', 'updater.js'),
    path.join(root, 'package.json'),
    path.join(root, '.github', 'workflows', 'release.yml'),
  ];
  const tokenRe = /ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}/;
  for (const f of srcFiles) {
    if (!fs.existsSync(f)) continue;
    const text = fs.readFileSync(f, 'utf8');
    assert(!tokenRe.test(text), 'token-like string in ' + path.relative(root, f));
  }
  console.log('PASS: no token strings in updater source');

  updater.resetStatusForTest();
  stub.app.isPackaged = false;
  delete process.env.MULTIHEIZ_FORCE_PACKAGED;
  delete process.env.MULTIHEIZ_FAKE_PORTABLE_FILE;
  let st = await updater.checkForUpdates({ silent: false });
  assert(st.status === 'dev', 'dev status');
  assert(/versão instalada/i.test(st.message), 'dev message');
  console.log('PASS: unpackaged check shows installed-only message');

  /* ---- Portable full flow with local fake feed ---- */
  clearUpdaterModules();
  const fakeBytes = Buffer.from('FAKE-PORTABLE-EXE-' + Date.now());
  const sha256 = crypto.createHash('sha256').update(fakeBytes).digest('hex');
  const remoteVer = '9.9.9';
  const assetName = `MultiHeiz-${remoteVer}-portable.exe`;
  const targetExe = path.join(tempRoot, 'MultiHeiz-1.0.1-portable.exe');
  fs.writeFileSync(targetExe, Buffer.from('OLD-EXE'));
  const markerPath = path.join(tempRoot, 'relaunched.marker');

  let serverPort = 0;
  const server = http.createServer((req, res) => {
    const url = req.url || '/';
    if (url === '/releases/latest' || url.startsWith('/releases/latest?')) {
      const body = JSON.stringify({
        tag_name: 'v' + remoteVer,
        assets: [
          {
            name: assetName,
            size: fakeBytes.length,
            digest: 'sha256:' + sha256,
            browser_download_url: `http://127.0.0.1:${serverPort}/download/${assetName}`,
            url: `http://127.0.0.1:${serverPort}/download/${assetName}`,
          },
          {
            name: 'latest.yml',
            size: 40,
            browser_download_url: `http://127.0.0.1:${serverPort}/latest.yml`,
          },
        ],
      });
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(body);
      return;
    }
    if (url === '/latest.yml') {
      res.writeHead(200, { 'Content-Type': 'text/yaml' });
      res.end(`version: ${remoteVer}\npath: MultiHeiz-${remoteVer}-setup.exe\nsha512: abc\n`);
      return;
    }
    if (url === '/bad-hash') {
      const body = JSON.stringify({
        tag_name: 'v' + remoteVer,
        assets: [
          {
            name: assetName,
            size: fakeBytes.length,
            digest: 'sha256:' + '0'.repeat(64),
            browser_download_url: `http://127.0.0.1:${serverPort}/download/${assetName}`,
            url: `http://127.0.0.1:${serverPort}/download/${assetName}`,
          },
        ],
      });
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(body);
      return;
    }
    if (url.startsWith('/download/')) {
      res.writeHead(200, {
        'Content-Type': 'application/octet-stream',
        'Content-Length': String(fakeBytes.length),
      });
      res.end(fakeBytes);
      return;
    }
    res.writeHead(404);
    res.end('no');
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  serverPort = server.address().port;

  process.env.MULTIHEIZ_UPDATE_FEED_URL = `http://127.0.0.1:${serverPort}/releases/latest`;
  process.env.MULTIHEIZ_FAKE_PORTABLE_FILE = targetExe;
  process.env.MULTIHEIZ_FORCE_PACKAGED = '1';
  process.env.MULTIHEIZ_PORTABLE_SKIP_PID_WAIT = '1';
  process.env.MULTIHEIZ_PORTABLE_RELAUNCH_CMD =
    `Set-Content -LiteralPath '${markerPath.replace(/'/g, "''")}' -Value 'ok' -Encoding utf8`;

  clearUpdaterModules();
  installElectronStub({
    isPackaged: true,
    version: '1.0.1',
    tempDir: tempRoot,
  });
  updater = require('../src/main/updater');
  updater.resetStatusForTest();

  assert(updater.detectUpdateChannel() === 'portable', 'fake portable channel');
  st = await updater.checkForUpdates({ silent: false });
  assert(st.status === 'available', 'portable available status: ' + st.status + ' ' + st.message);
  assert(st.version === remoteVer, 'portable remote version');
  assert(st.canDownload === true, 'canDownload');
  console.log('PASS: portable check finds newer version');

  st = await updater.downloadUpdate();
  assert(st.status === 'ready', 'portable ready: ' + st.status + ' / ' + st.message);
  assert(st.canInstall === true, 'canInstall after download');
  const dlPath = updater.portable.getDownloadedPath();
  assert(dlPath && fs.existsSync(dlPath), 'downloaded file exists');
  assert(fs.readFileSync(dlPath).equals(fakeBytes), 'downloaded bytes match');
  console.log('PASS: portable download + sha256 verify');

  const apply = updater.portable.applyPortableAndRelaunch({
    logger: console,
    skipQuit: true,
  });
  assert(apply.ok, 'apply ok: ' + (apply.error || ''));
  if (apply.child && typeof apply.child.on === 'function') {
    await new Promise((resolve) => {
      const t = setTimeout(resolve, 15000);
      apply.child.on('exit', () => {
        clearTimeout(t);
        resolve();
      });
      apply.child.on('error', () => {
        clearTimeout(t);
        resolve();
      });
    });
  } else {
    await new Promise((r) => setTimeout(r, 3000));
  }
  if (apply.logPath && fs.existsSync(apply.logPath)) {
    console.log('helper log:', fs.readFileSync(apply.logPath, 'utf8'));
  }
  assert(
    fs.existsSync(targetExe) && fs.readFileSync(targetExe).equals(fakeBytes),
    'target exe replaced by helper'
  );
  assert(fs.existsSync(markerPath), 'relaunch marker command ran');
  console.log('PASS: portable helper replaces file and relaunches marker');

  /* Hash mismatch */
  updater.portable.resetPortableStateForTest();
  process.env.MULTIHEIZ_UPDATE_FEED_URL = `http://127.0.0.1:${serverPort}/bad-hash`;
  const checked = await updater.portable.checkPortableUpdate({ logger: null });
  assert(checked.ok && checked.asset, 'bad-hash feed parsed');
  const bad = await updater.portable.downloadPortableAsset(checked.asset, { logger: null });
  assert(!bad.ok, 'hash mismatch should fail');
  assert(/Hash|SHA/i.test(bad.error || ''), 'hash error message: ' + bad.error);
  console.log('PASS: hash mismatch -> error');

  await new Promise((resolve) => server.close(resolve));

  delete process.env.MULTIHEIZ_UPDATE_FEED_URL;
  delete process.env.MULTIHEIZ_FAKE_PORTABLE_FILE;
  delete process.env.MULTIHEIZ_FORCE_PACKAGED;
  delete process.env.MULTIHEIZ_PORTABLE_SKIP_PID_WAIT;
  delete process.env.MULTIHEIZ_PORTABLE_RELAUNCH_CMD;

  try {
    fs.rmSync(tempRoot, { recursive: true, force: true });
  } catch {
    /* ignore */
  }

  console.log('PASS: selftest:updater complete');
  process.exit(0);
}

main().catch((err) => {
  console.log('FAIL:', err && err.message ? err.message : err);
  process.exit(1);
});
